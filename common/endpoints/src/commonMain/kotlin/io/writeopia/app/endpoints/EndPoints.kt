package io.writeopia.app.endpoints

object EndPoints {
    fun localAiGenerate() = "generate"

    fun localAiModels() = "api/tags"

    fun introNotes() = "document/intro"

    fun userNotes() = "document/user/{id}"

    fun documents() = "document"

    fun documentsByParent() = "document/parent/{id}"

    fun proxyUserNotes(userId: String = "{userId}") = "proxy/document/user/$userId"

    fun userNotes(userId: String = "{userId}") = "document/user/$userId"

    // Vertex AI endpoints
    fun aiGenerate() = "api/ai/generate"

    fun aiSummary() = "api/ai/summary"

    fun aiActionPoints() = "api/ai/action-points"

    fun aiFaq() = "api/ai/faq"

    fun aiTags() = "api/ai/tags"

    fun aiStatus() = "api/ai/status"

    fun aiUsage() = "api/ai/usage"

    /** POST the paragraph being written; the writing agent answers with the actions to offer. */
    fun aiWritingSuggestions() = "api/ai/writing-suggestions"

    /** POST a root document and the workspace folders; the agent answers which folders fit it. */
    fun aiFolderSuggestions() = "api/ai/folder-suggestions"

    /** POST a document and the workspace tags; Jev answers which tags fit it. */
    fun aiTagSuggestions() = "api/ai/tag-suggestions"

    /** POST a document; the cloud AI answers with a new tag (name and explanation) for it. */
    fun aiTagCreate() = "api/ai/tag-create"

    /** POST the tags of a workspace catalogue to upsert them. */
    fun documentTags() = "api/docs/workspace/tag"

    /** An image generated by the cloud AI for a paragraph, uploaded to the media storage. */
    fun aiImage() = "api/ai/image"

    /** POST a document; the cloud AI draws a header picture for it, served by the CDN. */
    fun aiHeaderImage() = "api/ai/header-image"

    /** The header pictures of a workspace: GET lists them, POST adds an approved one. */
    fun workspaceHeaderImages(workspaceId: String = "{workspaceId}") = "api/ai/header-images/$workspaceId"

    // Public, CDN-cacheable configuration for auto-configuring Local AI (Ollama / llmman)
    fun aiLocalConfig() = "api/ai/local-config"

    /** The presentations of a document: GET lists them, POST generates a new one. */
    fun documentPresentations(workspaceId: String = "{workspaceId}", documentId: String = "{documentId}") =
        "api/docs/workspace/$workspaceId/document/$documentId/presentations"

    /** One presentation: GET reads it, DELETE removes it. */
    fun presentation(workspaceId: String = "{workspaceId}", presentationId: String = "{presentationId}") =
        "api/docs/workspace/$workspaceId/presentation/$presentationId"

    // Public, CDN-cacheable latest desktop application version
    fun desktopAppVersion() = "auth/app/version"
}
